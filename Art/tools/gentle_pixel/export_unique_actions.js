#!/usr/bin/env node
/* Single export creates image assets, review strips, manifest, Swift frame plan
 * and the interactive review. Run --check in CI to detect stale output. */
'use strict';
const fs=require('fs'),path=require('path'),crypto=require('crypto');
const {png,rasterize,blit}=require('./pixel_io'), U=require('./unique_actions');
const root=path.resolve(__dirname,'../../..'), check=process.argv.includes('--check');
const out=path.join(root,'Art/gentle-pixel/launch-actions');
const catalog=path.join(root,'Apps/Shared/Sprites.xcassets');
const design=fs.readFileSync(path.join(root,'Packages/BatwalkCore/Sources/BatwalkCore/BatActions.swift'),'utf8').split('// MARK: Oddball')[0];
const cn=fs.readFileSync(path.join(root,'docs/BAT_ACTIONS.md'),'utf8');
const chineseNames=Object.fromEntries([...cn.matchAll(/`([^`]+)` \| ([^|]+) \|/g)].map(m=>[m[1],m[2].trim()]));
const actions=[...design.matchAll(/act\("([^"]+)", "([^"]+)", "([^"]+)", \.(\w+), \.(\w+),\s*"([^"]+)"/g)]
  .map(m=>({speciesID:m[1],actionID:m[2],name:m[3],chinese:chineseNames[m[2]]||m[3],tier:m[4],trigger:m[5],summary:m[6]}));
if(actions.length!==64||new Set(actions.map(a=>a.speciesID)).size!==20)throw Error('Launch design inventory changed');
const levels={hatchReveal:1,idleQuirk:2,reaction:3,signature:4,secret:5};
const manifest={version:1,logicalPixels:64,catalogPixels:128,clips:[]};
const swift=[];let newFrames=0;
function write(file,body){const data=Buffer.isBuffer(body)?body:Buffer.from(body);
  if(check){if(!fs.existsSync(file)||!fs.readFileSync(file).equals(data))throw Error('Stale or missing: '+path.relative(root,file));}
  else{fs.mkdirSync(path.dirname(file),{recursive:true});fs.writeFileSync(file,data);}}
for(const a of actions){
  const key=a.speciesID+'/'+a.actionID,old=a.actionID==='cartwheel-landing';
  let frames;
  if(a.speciesID==='mochi'){
    const times=old?[.25,.24,.24,1.2]:a.actionID==='thumb-ear-wash'?[.4,.5,.5,.4]:[.3,.45,.6,.4];
    frames=times.map((seconds,index)=>({seconds,index}));
  }else frames=U.frames(key);
  const prefix=old?'pilot_bat_':'unique_bat_';
  const names=frames.map(f=>prefix+a.speciesID+'_'+a.actionID+'_'+f.index);
  const hashes=[];
  const sheet={w:frames.length*128,h:128,rgba:Buffer.alloc(frames.length*128*128*4)};
  for(const f of frames){
    const dir=path.join(catalog,names[f.index]+'.imageset'),file=path.join(dir,'sprite.png');
    if(f.grid){
      const cell=rasterize(f.grid,2,null);
      write(file,png(cell.w,cell.h,cell.rgba));
      write(path.join(dir,'Contents.json'),JSON.stringify({images:[{filename:'sprite.png',idiom:'universal',scale:'2x'}],info:{author:'xcode',version:1}},null,2)+'\n');
      blit(sheet,rasterize(f.grid,2,[28,46,50]),f.index*128,0);
    }
    if(!fs.existsSync(file))throw Error('Run package_mochi_extras.py first: '+file);
    hashes.push(crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex'));
  }
  if(frames[0].grid)write(path.join(out,'strips',a.speciesID+'_'+a.actionID+'.png'),png(sheet.w,sheet.h,sheet.rgba));
  if(!old){swift.push('        '+JSON.stringify(key)+': ['+frames.map(f=>f.seconds).join(', ')+'],');newFrames+=frames.length;}
  manifest.clips.push({...a,unlockLevel:levels[a.tier],frames:names,seconds:frames.map(f=>f.seconds),sha256:hashes});
}
if(Object.keys(U.draw).length!==61)throw Error('Expected 61 code-native gestures');
write(path.join(out,'manifest.json'),JSON.stringify(manifest,null,2)+'\n');
write(path.join(root,'Packages/BatwalkCore/Sources/BatwalkCore/LaunchActionFrames.swift'),
  '// Generated by Art/tools/gentle_pixel/export_unique_actions.js. Do not edit.\n'+
  '// 63 new clips; Mochi cartwheel keeps its original pilot frames.\n'+
  'public enum LaunchActionFrames {\n    public static let seconds: [String: [Double]] = [\n'+swift.join('\n')+'\n    ]\n}\n');
const template=fs.readFileSync(path.join(__dirname,'unique_review.html'),'utf8');
write(path.join(out,'index.html'),template.replace('/* MANIFEST */',JSON.stringify(manifest)));
console.log(`${check?'Verified':'Exported'} 64 launch actions / ${newFrames} new frames + 4 existing Mochi frames.`);
